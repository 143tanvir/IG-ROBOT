'use strict';
const assert = require('node:assert/strict');
const { login } = require('../index');
const { attachIgBotCompatibility, IG_METHODS } = require('../src/igbot-compat');
assert.equal(typeof login, 'function');
assert.equal(typeof login.CookieUtils.parse, 'function');
const client = login.createClient({ logLevel: 'silent' });
assert.equal(typeof client.loginWithCookies, 'function');
assert.equal(typeof client.verifyTwoFactor, 'function');
assert.equal(typeof client.listen, 'function');
assert.equal(typeof client.destroy, 'function');
const fakeClient = { getCurrentUserID: () => ({ userID: '1' }), options: {} };
const fakeApi = {};
attachIgBotCompatibility(fakeApi, fakeClient);
assert.equal(typeof fakeApi.getThreadInfo, 'function');
assert.equal(typeof fakeApi.sendMessage, 'function');
assert.ok(fakeApi.getIGBotMethods().includes('getThreadInfo'));
assert.equal(fakeApi.getCompatibilityInfo().methods.length, IG_METHODS.length);
console.log('igbot-api compatibility smoke test passed');
